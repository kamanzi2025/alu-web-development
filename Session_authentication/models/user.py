#!/usr/bin/env python3
"""User module that defines the User model of the API."""
import hashlib
from models.base import Base


class User(Base):
    """User model with an email, a hashed password and a name."""

    def __init__(self, *args: list, **kwargs: dict):
        """Initialize a User instance from the given attributes."""
        super().__init__(*args, **kwargs)
        self.email = kwargs.get('email')
        self._password = kwargs.get('_password')
        self.first_name = kwargs.get('first_name')
        self.last_name = kwargs.get('last_name')

    @property
    def password(self) -> str:
        """Return the hashed password of the user."""
        return self._password

    @password.setter
    def password(self, pwd: str):
        """Hash the given clear password with SHA256 and store it."""
        if pwd is None or type(pwd) is not str:
            self._password = None
        else:
            self._password = hashlib.sha256(pwd.encode()).hexdigest().lower()

    def is_valid_password(self, pwd: str) -> bool:
        """Return True if the given clear password matches the stored one."""
        if pwd is None or type(pwd) is not str:
            return False
        if self.password is None:
            return False
        pwd_e = pwd.encode()
        return hashlib.sha256(pwd_e).hexdigest().lower() == self.password

    def display_name(self) -> str:
        """Return a display name built from the user's names or email."""
        if self.email is None and self.first_name is None \
                and self.last_name is None:
            return ""
        if self.first_name is None and self.last_name is None:
            return "{}".format(self.email)
        if self.last_name is None:
            return "{}".format(self.first_name)
        if self.first_name is None:
            return "{}".format(self.last_name)
        else:
            return "{} {}".format(self.first_name, self.last_name)
